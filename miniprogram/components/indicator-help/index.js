Component({
  properties: {
    label: { type: String, value: '' },
    tip: { type: String, value: '' },
  },

  data: {
    show: false,
    text: '',
  },

  lifetimes: {
    attached() {
      const text = this.properties.tip || DEFINITIONS[this.properties.label] || '暂无说明';
      this.setData({ text });
    },
  },

  methods: {
    onTap() {
      this.setData({ show: !this.data.show });
    },
    onClose() {
      this.setData({ show: false });
    },
  },
});
