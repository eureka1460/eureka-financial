/** 获取定义：精确匹配 → 去括号空格匹配 → 模糊匹配 */
function lookup(label) {
  if (!label) return '';
  // 精确匹配
  if (DEFINITIONS[label]) return DEFINITIONS[label];
  // 去空格匹配
  const stripped = label.replace(/\s+/g, '');
  for (const [k, v] of Object.entries(DEFINITIONS)) {
    if (k.replace(/\s+/g, '') === stripped) return v;
  }
  // 子串匹配（label 包含 key 或 key 包含 label）
  for (const [k, v] of Object.entries(DEFINITIONS)) {
    if (label.includes(k) || k.includes(label)) return v;
  }
  return '';
}

Component({
  properties: {
    label: { type: String, value: '' },
    tip: { type: String, value: '' },
  },

  data: {
    show: false,
    text: '',
  },

  lifetimes: {
    attached() {
      this.setData({
        text: this.properties.tip || lookup(this.properties.label) || '暂无说明',
      });
    },
  },

  methods: {
    onTap() {
      this.setData({ show: !this.data.show });
    },
    onClose() {
      this.setData({ show: false });
    },
  },
});
